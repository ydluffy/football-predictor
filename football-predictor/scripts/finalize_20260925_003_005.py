from __future__ import annotations

import csv
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
NOW = "2026-09-25T17:05:34+08:00"
PLAN_ID = "SPORTTERY_20260925_003_005_SAFE"


def rel(path: Path) -> str:
    return str(path.relative_to(ROOT)).replace("\\", "/")


def main() -> None:
    report_path = ROOT / "artifacts/betting/sporttery_final_analysis_2026-09-25_1705_003-005.md"
    audit_path = ROOT / "artifacts/data/sporttery_final_analysis_2026-09-25_1705_003-005.json"
    strategy_path = ROOT / "artifacts/data/sporttery_final_strategy_2026-09-25_1705_003-005_audit.json"
    plans_path = ROOT / "artifacts/data/sporttery_final_strategy_2026-09-25_1705_003-005_plans.csv"
    orchestration_path = ROOT / "artifacts/data/sporttery_final_orchestration_2026-09-25_1705_003-005.json"
    ledger_path = ROOT / "data/manual/betting_plan_ledger.csv"

    strategy = json.loads(strategy_path.read_text(encoding="utf-8"))
    orchestration = json.loads(orchestration_path.read_text(encoding="utf-8"))
    assert strategy["production_plan_rows"] == 1 and orchestration["ok"] is True
    with plans_path.open(encoding="utf-8-sig", newline="") as handle:
        plans = list(csv.DictReader(handle))
    formal = [p for p in plans if p["is_shadow"].lower() == "false"]
    assert len(formal) == 1
    source = formal[0]

    with ledger_path.open(encoding="utf-8-sig", newline="") as handle:
        existing = list(csv.DictReader(handle))
        fields = handle.seek(0) or next(csv.reader(handle))
    added = not any(row["plan_id"] == PLAN_ID for row in existing)
    if added:
        with ledger_path.open("a", encoding="utf-8", newline="") as handle:
            writer = csv.writer(handle)
            writer.writerow(
                [
                    "2026-09-25",
                    "18:00-18:30",
                    PLAN_ID,
                    "稳健",
                    source["selections"],
                    "100.00",
                    source["estimated_odds_min"],
                    "",
                    "待赛",
                    "",
                    "",
                    "",
                    "17:05硬锁前冻结；每组本金100元；正式策略及编排校验通过",
                ]
            )

    audit = json.loads(audit_path.read_text(encoding="utf-8"))
    audit.update(
        {
            "formal_plans": [
                {
                    "plan_id": PLAN_ID,
                    "type": "稳健",
                    "selections": source["selections"],
                    "stake": 100.0,
                    "estimated_odds": float(source["estimated_odds_min"]),
                    "estimated_payout": float(source["estimated_payout_min"]),
                }
            ],
            "formal_plan_reason": "one production-qualified safe plan generated by the mandatory strategy stage",
            "production_strategy_executed": True,
            "production_strategy_audit": rel(strategy_path),
            "production_plan_rows": 1,
            "production_ledger_write_performed": added,
            "production_ledger_plan_id": PLAN_ID,
            "orchestration_validation": orchestration,
            "external_odds": {
                "primary_source": "the_odds_api",
                "primary_status": "quota_insufficient",
                "effective_source": "nowscore",
                "effective_status": "available_via_nowscore",
                "captured_at": "2026-09-25T17:06:45+08:00",
                "mapped_matches": 3,
                "per_match": {
                    "003": "Australia +1.75 at 12 books (avg 1.98/1.82), with +1.5 and +2.0 outliers; external line is deeper than Sporttery +1 and strongly supports Brazil but warns about margin translation",
                    "004": "mapped but deep Asian quotes failed safe normalization; excluded from external directional inference",
                    "005": "Korea women -3.0 at 7 books (avg 1.94/1.80); aligns with Sporttery -3 while the away side price favors non-cover protection",
                },
                "production_model_feature_ready": False,
            },
        }
    )
    audit_path.write_text(json.dumps(audit, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    report = report_path.read_text(encoding="utf-8")
    report = report.replace(
        "本报告器只产生逐场市场分析与影子观察方案，不决定正式方案数。正式候选必须以同批 `build_multi_play_betting_strategy.py --stake 100` 的审计结果为准；影子模型或外盘缺失不得单独将正式方案置零。",
        f"正式策略及编排校验已通过，生成并入账1组稳健方案：{source['selections']}；本金100元，估算组合赔率{source['estimated_odds_min']}，预计返奖{source['estimated_payout_min']}元。价值正式0组。",
    )
    report += """

## 内外盘终版对照

- The Odds API余额不足，未发送必然失败的付费请求；捷报后备取得003—005唯一映射。
- 003澳大利亚受让主流+1.75（12家公司，主/客均价1.98/1.82），外盘比体彩+1更深：巴西胜面很强，但体彩让负与外盘赢两球门槛并不完全等价。
- 004韩国亚深盘报价未通过安全标准化，外盘不参与方向判断；体彩主胜1.03、-1让胜1.23均为极热方向。
- 005韩国女主流-3（7家公司，均价1.94/1.80），与体彩-3一致，但受让侧价格更低，支持让负保护。

## 冻结台账

- 正式稳健：003巴西客胜 + 004韩国亚主胜，本金100元，组合赔率1.1536，预计返奖115.36元。
- 正式价值：0组。
- 固定赔率影子：无符合6—10倍区间的低风险组合，未写入。
- 邪修影子：005(-3)让负@2.03，虚拟本金2元；与正式方案分开复盘。
"""
    report_path.write_text(report, encoding="utf-8")

    registry_path = ROOT / "artifacts/data/sporttery_task_registry_2026-09-25.json"
    registry = json.loads(registry_path.read_text(encoding="utf-8"))
    for task in registry["tasks"]:
        if task["key"] == "2026-09-25|18:00-18:30|终版分析":
            task.update(
                {
                    "status": "completed",
                    "completed_at": NOW,
                    "completion_status": "completed_ready_one_formal_safe_nowscore_available",
                    "artifact": rel(audit_path),
                    "report": rel(report_path),
                    "production_plan_rows": 1,
                    "production_ledger_write_performed": added,
                    "production_plan_ids": [PLAN_ID],
                }
            )
    registry["updated_at"] = NOW
    registry_path.write_text(json.dumps(registry, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    state_path = ROOT / "artifacts/data/football_automation_controller_state.json"
    state = json.loads(state_path.read_text(encoding="utf-8"))
    state.update(
        {
            "last_heartbeat_at": NOW,
            "last_completed_stage": "2026-09-25 18:00-18:30终版批次003-005",
            "last_completed_at": NOW,
            "last_stage_status": "completed_003_005_one_formal_safe_nowscore_available",
            "last_stage_artifact": rel(report_path),
            "last_ledger_write_at": NOW if added else state.get("last_ledger_write_at"),
            "next_required_stage": "2026-09-25 21:00终版分析006-013及晚间兜底",
            "next_required_at": "2026-09-25T21:00:00+08:00",
            "next_dynamic_task_key": "2026-09-25|00:00|终版分析",
            "next_dynamic_task_at": "2026-09-25T21:00:00+08:00",
        }
    )
    state["final_20260925_003_005"] = {
        "status": "completed",
        "completed_at": NOW,
        "scope": "003-005",
        "formal_strategy_executed": True,
        "formal_plan_count": 1,
        "formal_plan_ids": [PLAN_ID],
        "formal_stake": 100.0,
        "shadow_scheme_count": 7,
        "external_odds": "the_odds_quota_insufficient_nowscore_mapped3_of3",
        "production_ledger_write_performed": added,
        "report": rel(report_path),
        "review_due_at": "2026-09-26T13:00:00+08:00",
        "supabase_sync": "not_authorized_for_2026-09-25",
    }
    state_path.write_text(json.dumps(state, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": "completed", "scope": "003-005", "formal_rows": 1, "ledger_added": added, "plan_id": PLAN_ID}, ensure_ascii=False))


