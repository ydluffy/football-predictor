from __future__ import annotations

import csv
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
NOW = "2026-09-25T21:24:00+08:00"
PLAN_ID = "SPORTTERY_20260925_006_013_SAFE"


def rel(path: Path) -> str:
    return str(path.relative_to(ROOT)).replace("\\", "/")


def main() -> None:
    report_path = ROOT / "artifacts/betting/sporttery_final_analysis_2026-09-25_2122_006-013.md"
    audit_path = ROOT / "artifacts/data/sporttery_final_analysis_2026-09-25_2122_006-013.json"
    strategy_path = ROOT / "artifacts/data/sporttery_strategy_2026-09-25_2120_006-013.json"
    plans_path = ROOT / "artifacts/betting/sporttery_strategy_2026-09-25_2120_006-013_plans.csv"
    orchestration_path = ROOT / "artifacts/data/sporttery_final_orchestration_2026-09-25_2120_006-013.json"
    ledger_path = ROOT / "data/manual/betting_plan_ledger.csv"

    strategy = json.loads(strategy_path.read_text(encoding="utf-8"))
    orchestration = json.loads(orchestration_path.read_text(encoding="utf-8"))
    assert strategy["production_plan_rows"] == 1 and orchestration["ok"] is True
    with plans_path.open(encoding="utf-8-sig", newline="") as handle:
        formal = [row for row in csv.DictReader(handle) if row["is_shadow"].lower() == "false"]
    assert len(formal) == 1
    source = formal[0]

    with ledger_path.open(encoding="utf-8-sig", newline="") as handle:
        existing = list(csv.DictReader(handle))
    added = not any(row["plan_id"] == PLAN_ID for row in existing)
    if added:
        with ledger_path.open("a", encoding="utf-8", newline="") as handle:
            csv.writer(handle).writerow([
                "2026-09-25", "21:00-21:45", PLAN_ID, "稳健", source["selections"],
                "100.00", source["estimated_odds_min"], "", "待赛", "", "", "",
                "21:45硬锁前冻结；每组本金100元；正式策略及编排校验通过",
            ])

    audit = json.loads(audit_path.read_text(encoding="utf-8"))
    audit.update({
        "formal_plans": [{
            "plan_id": PLAN_ID, "type": "稳健", "selections": source["selections"],
            "stake": 100.0, "estimated_odds": float(source["estimated_odds_min"]),
            "estimated_payout": float(source["estimated_payout_min"]),
        }],
        "formal_plan_reason": "one production-qualified safe plan generated by the mandatory strategy stage",
        "production_strategy_executed": True,
        "production_strategy_audit": rel(strategy_path),
        "production_plan_rows": 1,
        "production_ledger_write_performed": added,
        "production_ledger_plan_id": PLAN_ID,
        "orchestration_validation": orchestration,
        "external_odds": {
            "primary_source": "the_odds_api", "primary_status": "quota_insufficient",
            "effective_source": "nowscore", "effective_status": "available_via_nowscore",
            "captured_at": "2026-09-25T21:17:55+08:00", "mapped_matches": 8,
            "captured_matches": 8, "quote_rows": 816, "asian_outer_rows": 136,
            "research_eligible_rows": 109, "failures": [],
            "production_model_feature_ready": False,
        },
        "unified_history_persistence": {
            "status": "deferred_file_locked",
            "pending_audit": "artifacts/data/unified_outer_market_pending/20260925T131907389020Z/audit.json",
        },
    })
    audit_path.write_text(json.dumps(audit, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    report = report_path.read_text(encoding="utf-8")
    report = report.replace(
        "外盘：鉴权探针HTTP 200，密钥有效，但当前仅余1 credit，不足以执行路由后的多市场刷新；本批0映射并排除。没有统一可核验的首发、伤停、xG或旅行负荷。",
        "外盘：The Odds API仅余1 credit，低于本批预计12 credits，未发送付费请求；捷报后备唯一映射8/8，取得816行六类报价、136行亚洲盘，其中109行满足赛前研究时效。外盘作为对照证据，未直接升级为生产模型特征。没有统一可核验的首发、伤停、xG或旅行负荷。",
    )
    report = report.replace(
        "本报告器只产生逐场市场分析与影子观察方案，不决定正式方案数。正式候选必须以同批 `build_multi_play_betting_strategy.py --stake 100` 的审计结果为准；影子模型或外盘缺失不得单独将正式方案置零。",
        f"正式策略及编排校验已通过，生成并入账1组稳健方案：{source['selections']}；本金100元，估算组合赔率{source['estimated_odds_min']}，预计返奖{source['estimated_payout_min']}元。价值正式0组。",
    )
    report += f"""

## 正式冻结与数据审计

- 正式稳健：{source['selections']}，本金100元，组合赔率{source['estimated_odds_min']}，预计返奖{source['estimated_payout_min']}元。
- 正式价值：0组；其余观察方案均保持影子属性。
- 固定赔率影子：006(-1)让负 + 007(-1)让负 + 012(-1)让胜，虚拟本金2元，组合赔率7.9944，已独立登记。
- 邪修影子：013(+1)让胜@1.77，虚拟本金2元，只作理论观察，不进入正式台账。
- 捷报后备已覆盖8/8；统一外盘历史因目标CSV被占用而进入待写目录，不能声称主历史已更新，但不影响本批体彩终版与冻结台账。
"""
    report_path.write_text(report, encoding="utf-8")

    registry_path = ROOT / "artifacts/data/sporttery_task_registry_2026-09-25.json"
    registry = json.loads(registry_path.read_text(encoding="utf-8"))
    for task in registry["tasks"]:
        if task["key"] in {"2026-09-25|00:00|终版分析", "2026-09-25|02:45-03:00|终版分析"}:
            task.update({
                "status": "completed", "completed_at": NOW,
                "completion_status": "completed_ready_one_formal_safe_nowscore_available",
                "artifact": rel(audit_path), "report": rel(report_path),
                "production_plan_rows": 1, "production_ledger_write_performed": added,
                "production_plan_ids": [PLAN_ID],
            })
    registry["updated_at"] = NOW
    registry_path.write_text(json.dumps(registry, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    state_path = ROOT / "artifacts/data/football_automation_controller_state.json"
    state = json.loads(state_path.read_text(encoding="utf-8"))
    state.update({
        "last_heartbeat_at": NOW,
        "last_completed_stage": "2026-09-25 21:00终版批次006-013及晚间兜底",
        "last_completed_at": NOW,
        "last_stage_status": "completed_006_013_one_formal_safe_nowscore_available",
        "last_stage_artifact": rel(report_path),
        "last_ledger_write_at": NOW if added else state.get("last_ledger_write_at"),
        "next_required_stage": "2026-09-26 10:00开售前预扫描",
        "next_required_at": "2026-09-26T10:00:00+08:00",
        "next_dynamic_task_key": None, "next_dynamic_task_at": None,
        "inner_outer_alignment_status": "2026-09-25_2117_primary_quota_insufficient_nowscore_mapped8_of8_research_rows109",
    })
    state["final_20260925_006_013"] = {
        "status": "completed", "completed_at": NOW, "scope": "006-013",
        "formal_strategy_executed": True, "formal_plan_count": 1,
        "formal_plan_ids": [PLAN_ID], "formal_stake": 100.0,
        "shadow_scheme_count": 10,
        "external_odds": "the_odds_quota_insufficient_nowscore_mapped8_of8",
        "production_ledger_write_performed": added, "report": rel(report_path),
        "review_due_at": "2026-09-26T13:00:00+08:00",
        "supabase_sync": "not_authorized_for_2026-09-25",
    }
    state_path.write_text(json.dumps(state, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"status": "completed", "scope": "006-013", "formal_rows": 1, "ledger_added": added, "plan_id": PLAN_ID}, ensure_ascii=False))


if __name__ == "__main__":
    main()
